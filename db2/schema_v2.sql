-- Mainframe Banking V2 schema (lab)
-- Synthetic educational model. Not a real bank.

CREATE TABLE BANK_CIF (
  CIF_NO        CHAR(10) NOT NULL PRIMARY KEY,
  CUSTOMER_NAME VARCHAR(30),
  ADDRESS       VARCHAR(50),
  KYC_STAT      CHAR(1),
  REL_MGR       CHAR(8)
);

CREATE TABLE BANK_CUSTOMER (
  ACCOUNT_NO    CHAR(6) NOT NULL PRIMARY KEY,
  CIF_NO        CHAR(10),
  CUSTOMER_NAME VARCHAR(30),
  STATUS        CHAR(1),
  BRANCH_NO     CHAR(6),
  REGION        CHAR(4),
  BALANCE       DECIMAL(15,2),
  HOLD_AMT      DECIMAL(15,2),
  OD_LIMIT      DECIMAL(15,2),
  LAST_POST_TS  TIMESTAMP,
  OPEN_DTE      DATE,
  CCY           CHAR(3) DEFAULT 'USD'
);

CREATE TABLE BANK_JOURNAL (
  TRACE_ID      VARCHAR(26) NOT NULL PRIMARY KEY,
  ACCOUNT_NO    CHAR(6),
  LOC_ID        CHAR(8),
  CHANNEL       CHAR(8),
  DR_CR         CHAR(1),
  AMOUNT        DECIMAL(15,2),
  CYCLE_DTE     DATE,
  POSTED_IND    CHAR(1),
  REVERSAL_OF   VARCHAR(26),
  TERM_ID       CHAR(8),
  TELLER_ID     CHAR(8),
  CREATE_TS     TIMESTAMP DEFAULT CURRENT TIMESTAMP,
  POST_TS       TIMESTAMP,
  NARR          VARCHAR(40)
);
CREATE INDEX IX_JRN_ACC ON BANK_JOURNAL(ACCOUNT_NO);
CREATE INDEX IX_JRN_CYC ON BANK_JOURNAL(CYCLE_DTE, LOC_ID);
CREATE INDEX IX_JRN_TRACE ON BANK_JOURNAL(TRACE_ID);

CREATE TABLE BANK_LOCATION_FILE_CTL (
  LOC_ID         CHAR(8) NOT NULL,
  CYCLE_DTE      DATE NOT NULL,
  GEN_NO         INTEGER,
  ARRIVED_IND    CHAR(1),
  VALIDATED_IND  CHAR(1),
  HASH_DR        DECIMAL(17,2),
  HASH_CR        DECIMAL(17,2),
  REC_COUNT      INTEGER,
  DSNAME         VARCHAR(44),
  PRIMARY KEY (LOC_ID, CYCLE_DTE)
);

CREATE TABLE BANK_LOCATION_XTR (
  TRACE_ID    VARCHAR(26) NOT NULL PRIMARY KEY,
  LOC_ID      CHAR(8),
  CYCLE_DTE   DATE,
  ACCOUNT_NO  CHAR(6),
  DR_CR       CHAR(1),
  AMOUNT      DECIMAL(15,2),
  CHANNEL     CHAR(8)
);

CREATE TABLE BANK_RECON_XCPT (
  XCPT_ID     INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  CYCLE_DTE   DATE,
  LOC_ID      CHAR(8),
  TRACE_ID    VARCHAR(26),
  ACCOUNT_NO  CHAR(6),
  REASON      VARCHAR(16),
  AMOUNT      DECIMAL(15,2),
  STATUS      CHAR(1)
);

CREATE TABLE BANK_CYCLE_CTL (
  CYCLE_DTE        DATE NOT NULL PRIMARY KEY,
  STATUS           CHAR(8),
  ONLINE_INHIBIT   CHAR(1),
  VALIDATED_IND    CHAR(1),
  RECON_CLOSED     CHAR(1),
  LOCK_OWNER       CHAR(8)
);

CREATE TABLE BANK_RESTART (
  CYCLE_DTE   DATE NOT NULL PRIMARY KEY,
  LAST_TRACE  VARCHAR(26),
  CHUNK_NO    INTEGER,
  MODE        CHAR(8)
);

CREATE TABLE BANK_HOLD (
  HOLD_ID     CHAR(12) NOT NULL PRIMARY KEY,
  ACCOUNT_NO  CHAR(6),
  AMOUNT      DECIMAL(15,2),
  REASON      VARCHAR(20),
  EXP_DTE     DATE,
  STATUS      CHAR(1)
);

CREATE TABLE BANK_ATM_ADVICE (
  TRACE_ID    VARCHAR(26) NOT NULL PRIMARY KEY,
  PAN_HASH    CHAR(16),
  TERM_ID     CHAR(8),
  AMOUNT      DECIMAL(15,2),
  DISP_IND    CHAR(1),
  REV_OF      VARCHAR(26),
  SWITCH_TS   TIMESTAMP,
  CASSETTE    CHAR(4)
