  GL_ACCT     CHAR(10),
  CCY         CHAR(3),
  DR_CR       CHAR(1),
  AMOUNT      DECIMAL(15,2),
  SRC_LOC     CHAR(8),
  NARR        VARCHAR(40)
);

CREATE TABLE BANK_TELLER (
  TELLER_ID     CHAR(8) NOT NULL PRIMARY KEY,
  BRANCH_NO     CHAR(6),
  DRAWER_CASH   DECIMAL(15,2),
  SIGNED_ON     CHAR(1),
  OVERRIDE_LVL  INTEGER
